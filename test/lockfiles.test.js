test('bun.lock: JSONC tolerated, workspace entries skipped, edges from meta', () => {
  const parsed = parseBunLock([
    '// bun lockfile',
    '{',
    '  "lockfileVersion": 1,',
    '  "packages": {',
    '    "chalk": ["chalk@5.3.0", "", { "dependencies": { "ansi": "^1.0.0" } }, "sha512-xxx"],',
    '    "@scope/x": ["@scope/x@1.0.0"],',
    '    "myws": ["myws@workspace:packages/myws"],',
    '  },',
    '}',
  ].join('\n'));
  assert.deepStrictEqual(byKey(parsed), { chalk: '5.3.0', '@scope/x': '1.0.0' });
  assert.deepStrictEqual(edgeObj(parsed), { chalk: ['ansi'] });
});

test('viaChain walks reverse edges to a top-level package', () => {
  const edges = new Map([
    ['a', new Set(['b'])],
    ['b', new Set(['c'])],
    ['other', new Set(['b'])],
  ]);
  assert.deepStrictEqual(viaChain(edges, 'c'), ['a', 'b']);
  assert.deepStrictEqual(viaChain(edges, 'a'), []);
  // cycles do not hang
  const cyc = new Map([['x', new Set(['y'])], ['y', new Set(['x'])]]);
  assert.deepStrictEqual(viaChain(cyc, 'x'), ['y']);
});

test('resolveLockfile: type detection and directory search order', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'lens-lock-'));
  fs.writeFileSync(path.join(tmp, 'bun.lock'), '{"lockfileVersion":1,"packages":{}}');
  assert.strictEqual(resolveLockfile(tmp).type, 'bun');
  fs.writeFileSync(path.join(tmp, 'yarn.lock'), '# yarn lockfile v1\n');
  assert.strictEqual(resolveLockfile(tmp).type, 'yarn', 'yarn.lock outranks bun.lock');
  fs.writeFileSync(path.join(tmp, 'pnpm-lock.yaml'), "lockfileVersion: '9.0'\n");
  assert.strictEqual(resolveLockfile(tmp).type, 'yarn', 'yarn.lock outranks pnpm-lock.yaml');
  fs.writeFileSync(path.join(tmp, 'package-lock.json'), '{"lockfileVersion":3,"packages":{}}');
  assert.strictEqual(resolveLockfile(tmp).type, 'npm', 'package-lock.json outranks all');
  assert.strictEqual(resolveLockfile(path.join(tmp, 'pnpm-lock.yaml')).type, 'pnpm');
  assert.throws(() => resolveLockfile(path.join(tmp, 'nope')), /lockfile not found/);
  const only = fs.mkdtempSync(path.join(os.tmpdir(), 'lens-bunb-'));
  fs.writeFileSync(path.join(only, 'bun.lockb'), 'binary');
  assert.throws(() => resolveLockfile(only), /save-text-lockfile/);
});
